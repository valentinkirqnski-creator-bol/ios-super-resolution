"""Extract rob_gcam_guide / rob_gcam_prefilter / gcam_lut_sample from HHSRKernels.metal and translate them
mechanically to C++ (gguide_emu.inc), so the CPU emulation runs the SAME source text as the device."""
import re
import sys

src = open(sys.argv[1], encoding="utf8").read()


def grab(start_pat):
    i = src.index(start_pat)
    j = src.index("{", i)
    depth, k = 0, j
    while True:
        if src[k] == "{":
            depth += 1
        elif src[k] == "}":
            depth -= 1
            if depth == 0:
                return src[i:k + 1]
        k += 1


parts = [grab("inline float gcam_lut_sample("),
         src[src.index("struct GcamGuideParams {"):src.index("};", src.index("struct GcamGuideParams {")) + 2],
         grab("kernel void rob_gcam_guide("),
         grab("kernel void rob_gcam_prefilter(")]
code = "\n\n".join(parts)
code = re.sub(r"\s*\[\[[^\]]*\]\]", "", code)              # attributes
code = code.replace("kernel void", "static void")
code = code.replace("device const ", "const ").replace("device ", "")
code = code.replace("constant GcamGuideParams&", "const GcamGuideParams&").replace("constant uint2&", "const U2&")
code = code.replace("uint2 gid", "U2 gid")
code = code.replace("precise::sqrt", "std::sqrt").replace("fabs(", "std::fabs(")
code = re.sub(r"\buint\b", "uint32_t", code)
code = re.sub(r"(?<![\w:])max\(", "mx(", code)
code = re.sub(r"(?<![\w:])min\(", "mn(", code)
code = re.sub(r"(?<![\w:])clamp\(", "cl(", code)
code = re.sub(r"(?<![\w:])floor\(", "std::floor(", code)
hdr = """// GENERATED by mk_gguide_emu.py from HHSRKernels.metal -- do not edit.
struct U2 { uint32_t x, y; };
static inline float mx(float a, float b) { return a > b ? a : b; }
static inline int mx(int a, int b) { return a > b ? a : b; }
static inline float mn(float a, float b) { return a < b ? a : b; }
static inline int mn(int a, int b) { return a < b ? a : b; }
static inline float cl(float v, float lo, float hi) { return v < lo ? lo : (v > hi ? hi : v); }
static inline int cl(int v, int lo, int hi) { return v < lo ? lo : (v > hi ? hi : v); }
"""
open(sys.argv[2], "w", encoding="utf8").write(hdr + code + "\n")
print("wrote", sys.argv[2])
