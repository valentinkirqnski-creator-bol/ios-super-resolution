"""Export a trained model to cpp/robust_nn_weights.h (standardisation folded into layer 1).

    python export_weights.py --model runs/v1/model.pt
"""
import argparse
import os
import sys

import torch

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rnn.model import RobustNet, RobustNetTile, HID   # noqa: E402
from rnn.features import NF, NAMES     # noqa: E402


def arr(name, t):
    v = t.detach().reshape(-1).tolist()
    body = ",\n    ".join(", ".join(f"{x:.9g}f" for x in v[i:i + 8]) for i in range(0, len(v), 8))
    return f"RNN_CONSTANT float {name}[{len(v)}] = {{\n    {body}\n}};\n"


def write_header(net, path, note=""):
    w1, b1 = net.folded()
    n_params = sum(p.numel() for p in net.parameters())
    tile = isinstance(net, RobustNetTile)
    b2 = net.c2.bias + net.k3.bias if tile else net.c2.bias   # the tile term's bias folded into layer 2
    nf = net.c1.weight.shape[1]                       # the net's inputs (a 14-input net ships 14 features)
    s = ["// GENERATED by tools/robust_nn/export_weights.py -- do not edit.",
         f"// {note}",
         f"// {n_params} parameters. Features: {', '.join(NAMES[:nf])}",
         "#pragma once",
         f"#define RNN_NF {nf}",
         f"#define RNN_HID {net.c1.weight.shape[0]}",
         f"#define RNN_CTX {net.k1.weight.shape[0] if tile else 0}",
         "// W1 layout [hid][feature][ky][kx]; standardisation already folded in.",
         arr("RNN_W1", w1), arr("RNN_B1", b1),
         arr("RNN_W2", net.c2.weight), arr("RNN_B2", b2),
         arr("RNN_W3", net.c3.weight), arr("RNN_B3", net.c3.bias)]
    if tile:
        # v31 (rnn/model.py RobustNetTile): the mean and max of the STANDARDISED features over the pixel's flow
        # tile -> K1 (1x1, [ctx][avg 14 | max 14]) -> ReLU -> K2 (3x3 over the tile grid, clamp-to-edge,
        # [ctx][ctx][ky][kx]) -> ReLU -> K3 ([hid][ctx]) added to layer 2 before its ReLU (bias folded into RNN_B2).
        s += ["// tile branch: standardisation of the pooled features, then K1 / K2 / K3 (see core/robust_nn_shared.h)",
              arr("RNN_MU", net.mu), arr("RNN_SD", net.sd),
              arr("RNN_K1", net.k1.weight), arr("RNN_BK1", net.k1.bias),
              arr("RNN_K2", net.k2.weight), arr("RNN_BK2", net.k2.bias),
              arr("RNN_K3", net.k3.weight)]
    open(path, "w").write("\n".join(s))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="runs/v1/model.pt")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "core",
                                                  "robust_nn_weights.h"))
    a = ap.parse_args()
    if a.model != "identity":
        sd = torch.load(a.model, map_location="cpu")
        if "tile_model" in sd:
            net = RobustNetTile(nf=sd["c1.weight"].shape[1], hid=sd["c1.weight"].shape[0], ctx=sd["k1.weight"].shape[0])
        else:
            net = RobustNet(nf=sd["c1.weight"].shape[1], hid=sd["c1.weight"].shape[0])
        net.load_state_dict(sd)
    else:
        net = RobustNet()
    write_header(net, a.out, f"source: {a.model}")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
