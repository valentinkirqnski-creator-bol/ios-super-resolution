"""Export v15 (PixNet over its own v14 base) to core/robust_nn15_weights.h for the app's banded Metal kernels.

    python export_v15.py --model runs/v15b/pix_s15000.pt --shift -0.75
The logit shift (the chosen operating point) is folded into the head bias. The base is the v14 the PixNet was
trained on, exported under its own RNN15B_ names so a later change of the main robust_nn weights (v17, ...) cannot
silently change v15's base.
"""
import argparse
import os
import sys

import torch

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from real_protocol import load_net                       # noqa: E402
from rnn.pixnet import PixNet, NPIX                      # noqa: E402


def arr(name, t):
    v = t.detach().reshape(-1).tolist()
    body = ",\n    ".join(", ".join(f"{x:.9g}f" for x in v[i:i + 8]) for i in range(0, len(v), 8))
    return f"RNN_CONSTANT float {name}[{len(v)}] = {{\n    {body}\n}};\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="runs/v15b/model.pt")
    ap.add_argument("--base", default="runs/v14/model.pt")
    ap.add_argument("--shift", type=float, default=-0.75)
    ap.add_argument("--out", default=os.path.join(HERE, "..", "..", "core", "robust_nn15_weights.h"))
    a = ap.parse_args()
    base = load_net(os.path.join(HERE, a.base))
    sd = torch.load(os.path.join(HERE, a.model), map_location="cpu")
    net = PixNet(base, ch=sd["p1.weight"].shape[0])
    net.load_state_dict(sd)
    ch, cin = net.p1.weight.shape[0], net.p1.weight.shape[1]
    nf = base.c1.weight.shape[1]
    assert cin == nf + NPIX + 1, "v15 export expects the 4-channel (no consensus) PixNet"
    for m, d in ((net.p1, 1), (net.p2, 2), (net.p3, 4), (net.p4, 1)):
        assert m.dilation == (d, d) and m.padding_mode == "replicate"
    w1, b1 = base.folded()
    n_params = sum(p.numel() for p in net.parameters())
    s = ["// GENERATED by tools/robust_nn/export_v15.py -- do not edit.",
         f"// source: {a.model} over base {a.base}, logit shift {a.shift:+.3f} folded into RNN15_B5",
         f"// {n_params} parameters (base + pixel net). Layout: conv weights [out][in][ky][kx].",
         "#pragma once",
         f"#define RNN15_NF {nf}",
         f"#define RNN15_NPIX {NPIX}",
         f"#define RNN15_CIN {cin}",
         f"#define RNN15_CH {ch}",
         f"#define RNN15B_HID {base.c1.weight.shape[0]}",
         "// base (v14) with its standardisation folded into layer 1",
         arr("RNN15B_W1", w1), arr("RNN15B_B1", b1), arr("RNN15B_W2", base.c2.weight), arr("RNN15B_B2", base.c2.bias),
         arr("RNN15B_W3", base.c3.weight), arr("RNN15B_B3", base.c3.bias),
         "// pixel net: input standardisation of the 14 features, 4 dilated 3x3 convs (1,2,4,1), 1x1 head",
         arr("RNN15_MU", base.mu), arr("RNN15_SD", base.sd),
         arr("RNN15_W1", net.p1.weight), arr("RNN15_B1", net.p1.bias),
         arr("RNN15_W2", net.p2.weight), arr("RNN15_B2", net.p2.bias),
         arr("RNN15_W3", net.p3.weight), arr("RNN15_B3", net.p3.bias),
         arr("RNN15_W4", net.p4.weight), arr("RNN15_B4", net.p4.bias),
         arr("RNN15_W5", net.p5.weight), arr("RNN15_B5", net.p5.bias + a.shift)]
    open(a.out, "w").write("\n".join(s))
    print("wrote", a.out, n_params, "params")


if __name__ == "__main__":
    main()
