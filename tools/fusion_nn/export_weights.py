"""Export a FusionNet (r1 architecture) checkpoint to core/fusion_nn_weights.h.

    python export_weights.py <model.pt> <out.h> [--c 12] [--cin 8]
"""
import argparse

import torch

import fusion as fu


def arr(name, t):
    v = t.detach().float().reshape(-1).tolist()
    body = ",".join(("%.9g" % x) + ("f" if "." in ("%.9g" % x) or "e" in ("%.9g" % x) else ".f") for x in v)
    return "FNN_CONSTANT float %s[%d] = {%s};\n" % (name, len(v), body)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("model")
    ap.add_argument("out")
    ap.add_argument("--c", type=int, default=12)
    ap.add_argument("--cin", type=int, default=8)
    a = ap.parse_args()
    net = fu.FusionNet(c=a.c, cin=a.cin)
    net.load_state_dict(torch.load(a.model))
    dil = [b.dw.dilation[0] for b in net.blocks]
    s = ["// Generated by tools/fusion_nn/export_weights.py from %s -- do not edit.\n" % a.model.replace("\\", "/"),
         "// FusionNet (tools/fusion_nn/fusion.py): stem 3x3 %d->%d, %d residual depthwise-separable blocks\n" % (a.cin, a.c, len(dil)),
         "// (3x3 depthwise, dilations %s, then 1x1 %d->%d, ReLU), head 1x1 %d->1. PyTorch layouts:\n" % (dil, a.c, a.c, a.c),
         "// conv weight [out][in][ky][kx], depthwise [c][ky][kx], pointwise [out][in].\n",
         "#pragma once\n",
         "#ifndef FNN_CONSTANT\n#define FNN_CONSTANT static const\n#endif\n",
         "#define FNN_CIN %d\n#define FNN_C %d\n#define FNN_NBLOCKS %d\n" % (a.cin, a.c, len(dil)),
         "FNN_CONSTANT int fnn_dil[%d] = {%s};\n" % (len(dil), ",".join(str(d) for d in dil)),
         arr("fnn_stem_w", net.stem.weight), arr("fnn_stem_b", net.stem.bias)]
    for i, b in enumerate(net.blocks):
        s += [arr("fnn_dw%d_w" % i, b.dw.weight), arr("fnn_dw%d_b" % i, b.dw.bias),
              arr("fnn_pw%d_w" % i, b.pw.weight), arr("fnn_pw%d_b" % i, b.pw.bias)]
    s += [arr("fnn_head_w", net.head.weight), arr("fnn_head_b", net.head.bias)]
    s.append("static const float* const fnn_dw_w[%d] = {%s};\n" % (len(dil), ",".join("fnn_dw%d_w" % i for i in range(len(dil)))))
    s.append("static const float* const fnn_dw_b[%d] = {%s};\n" % (len(dil), ",".join("fnn_dw%d_b" % i for i in range(len(dil)))))
    s.append("static const float* const fnn_pw_w[%d] = {%s};\n" % (len(dil), ",".join("fnn_pw%d_w" % i for i in range(len(dil)))))
    s.append("static const float* const fnn_pw_b[%d] = {%s};\n" % (len(dil), ",".join("fnn_pw%d_b" % i for i in range(len(dil)))))
    open(a.out, "w", newline="\n").write("".join(s))
    print("wrote", a.out, sum(p.numel() for p in net.parameters()), "params")


if __name__ == "__main__":
    main()
