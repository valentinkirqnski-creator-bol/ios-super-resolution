"""Export a trained ConfNet to a C/Metal weights header (cpp/app/conf_nn_weights.h by default; integrate_app.py
copies it into core/ when the network is wired into the app).

    python export_weights.py runs/m9_guideres/best.pt [--out ../../core/conf_nn_weights.h]

The input standardisation (mu / sd buffers) is folded into the first guide-res conv and into the raw-res conv's input
channels; with replicate padding this is exact. Layout: conv weights [out][in][ky][kx], 1x1 weights [out][in].
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import torch                        # noqa: E402

from mfsr import model as M         # noqa: E402
from mfsr.inputs import NG, NR      # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))


def fold(conv_w, conv_b, mu, sd, ch_slice):
    """W' = W / sd, b' = b - sum W * mu / sd over the standardised input channels ch_slice."""
    w = conv_w.clone()
    b = conv_b.clone()
    s = slice(*ch_slice)
    w[:, s] = conv_w[:, s] / sd.view(1, -1, 1, 1)
    b = b - (conv_w[:, s] * (mu / sd).view(1, -1, 1, 1)).sum((1, 2, 3))
    return w, b


def arr(name, t):
    v = t.detach().double().reshape(-1).tolist()
    body = ",\n".join("    " + ", ".join(f"{x:.9e}f" for x in v[i:i + 8]) for i in range(0, len(v), 8))
    return f"CNN_CONST float {name}[{len(v)}] = {{\n{body}\n}};\n"


def export(net, cfg_model, path, tag=""):
    net = net.eval()
    ch, up = net.ch, net.up_ch
    dils = [c.dilation[0] for c in net.enc]
    w0, b0 = fold(net.enc[0].weight, net.enc[0].bias, net.mu_g, net.sd_g, (0, NG))
    L = ["// conf_nn_weights.h -- GENERATED by tools/mfsr_conf/export_weights.py, do not edit.",
         f"// {tag}", "#pragma once", "",
         "#ifdef __METAL_VERSION__", "#define CNN_CONST constant", "#else", "#define CNN_CONST static const", "#endif",
         "", f"#define CNN_NG {NG}", f"#define CNN_NR {NR}", f"#define CNN_CH {ch}", f"#define CNN_UP {up}",
         f"#define CNN_FUSION {1 if net.fusion else 0}", f"#define CNN_USE_R0 {1 if cfg_model.get('use_r0') or cfg_model.get('refine_r0') else 0}",
         f"#define CNN_REFINE_R0 {1 if net.refine_r0 else 0}"]
    for i, d in enumerate(dils):
        L.append(f"#define CNN_DIL{i} {d}")
    L.append("")
    L.append(arr("CNN_E0_W", w0))
    L.append(arr("CNN_E0_B", b0))
    for i in range(1, 4):
        L.append(arr(f"CNN_E{i}_W", net.enc[i].weight))
        L.append(arr(f"CNN_E{i}_B", net.enc[i].bias))
    L.append(arr("CNN_F1_W", net.f1.weight))
    L.append(arr("CNN_F1_B", net.f1.bias))
    L.append(arr("CNN_F2_W", net.f2.weight))
    L.append(arr("CNN_F2_B", net.f2.bias))
    L.append(arr("CNN_HD_W", net.head.weight))
    L.append(arr("CNN_HD_B", net.head.bias))
    if up > 0:
        nin = up + NR + 2
        w1, b1 = fold(net.u1.weight, net.u1.bias, net.mu_r, net.sd_r, (up, up + NR))
        L.append(arr("CNN_U0_W", net.u0.weight))
        L.append(arr("CNN_U0_B", net.u0.bias))
        L.append(arr("CNN_U1_W", w1))
        L.append(arr("CNN_U1_B", b1))
        L.append(arr("CNN_U2_W", net.u2.weight))
        L.append(arr("CNN_U2_B", net.u2.bias))
        L.append(f"#define CNN_U1_IN {nin}")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("model")
    ap.add_argument("--out", default=os.path.join(HERE, "cpp", "app", "conf_nn_weights.h"))
    a = ap.parse_args()
    ck = torch.load(a.model, map_location="cpu", weights_only=False)
    net = M.build(ck["cfg"]["model"])
    net.load_state_dict(ck["state"])
    export(net, ck["cfg"]["model"], a.out, tag=f"{a.model} step {ck.get('step')}")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
